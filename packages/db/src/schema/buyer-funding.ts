import { sql } from "drizzle-orm";
import { blob, check, index, integer, sqliteTable, text, uniqueIndex } from "drizzle-orm/sqlite-core";

/** Append-only, block-pinned observations; lookups use finalized rows only. */
export const escrowFunding = sqliteTable(
  "escrow_funding",
  {
    id: integer("id").primaryKey(),
    scopeId: text("scope_id").notNull(),
    chainId: integer("chain_id").notNull(),
    escrow: text("escrow").notNull(),
    buyer: text("buyer").notNull(),
    operator: text("operator").notNull(),
    finality: text("finality", { enum: ["latest", "finalized"] }).notNull(),
    blockNumber: text("block_number").notNull(),
    blockHash: text("block_hash").notNull(),
    fundingBlockNumber: text("funding_block_number").notNull(),
    fundingBlockHash: text("funding_block_hash").notNull(),
    fundedAt: integer("funded_at").notNull(),
    verifierVersion: text("verifier_version").notNull(),
    verifiedAt: text("verified_at").notNull(),
  },
  (t) => ({
    scopeIdCheck: check("escrow_funding_scope_id_check", sql`length(scope_id) BETWEEN 1 AND 200`),
    chainIdCheck: check("escrow_funding_chain_id_check", sql`chain_id > 0`),
    escrowCheck: check("escrow_funding_escrow_check", sql`escrow = lower(escrow) AND length(escrow) = 42 AND substr(escrow,1,2) = '0x' AND substr(escrow,3) NOT GLOB '*[^0-9a-f]*' AND escrow <> '0x0000000000000000000000000000000000000000'`),
    buyerCheck: check("escrow_funding_buyer_check", sql`buyer = lower(buyer) AND length(buyer) = 42 AND substr(buyer,1,2) = '0x' AND substr(buyer,3) NOT GLOB '*[^0-9a-f]*' AND buyer <> '0x0000000000000000000000000000000000000000'`),
    operatorCheck: check("escrow_funding_operator_check", sql`operator = lower(operator) AND length(operator) = 42 AND substr(operator,1,2) = '0x' AND substr(operator,3) NOT GLOB '*[^0-9a-f]*' AND operator <> '0x0000000000000000000000000000000000000000'`),
    finalityCheck: check("escrow_funding_finality_check", sql`finality IN ('latest', 'finalized')`),
    blockNumberCheck: check("escrow_funding_block_number_check", sql`block_number NOT GLOB '*[^0-9]*' AND length(block_number) BETWEEN 1 AND 20 AND (block_number = '0' OR substr(block_number,1,1) <> '0')`),
    blockHashCheck: check("escrow_funding_block_hash_check", sql`block_hash = lower(block_hash) AND length(block_hash) = 66 AND substr(block_hash,1,2) = '0x' AND substr(block_hash,3) NOT GLOB '*[^0-9a-f]*'`),
    fundingBlockNumberCheck: check("escrow_funding_funding_block_number_check", sql`funding_block_number NOT GLOB '*[^0-9]*' AND length(funding_block_number) BETWEEN 1 AND 20 AND (funding_block_number = '0' OR substr(funding_block_number,1,1) <> '0')`),
    fundingBlockHashCheck: check("escrow_funding_funding_block_hash_check", sql`funding_block_hash = lower(funding_block_hash) AND length(funding_block_hash) = 66 AND substr(funding_block_hash,1,2) = '0x' AND substr(funding_block_hash,3) NOT GLOB '*[^0-9a-f]*'`),
    fundedAtCheck: check("escrow_funding_funded_at_check", sql`funded_at > 0`),
    verifierVersionCheck: check("escrow_funding_verifier_version_check", sql`length(verifier_version) BETWEEN 1 AND 100`),
    finalScope: uniqueIndex("escrow_funding_final_scope_uq").on(t.scopeId).where(sql`${t.finality} = 'finalized'`),
    finalEscrow: uniqueIndex("escrow_funding_final_escrow_uq").on(t.chainId, t.escrow).where(sql`${t.finality} = 'finalized'`),
  }),
);

/** Prepare identity and terms freeze at insert; lifecycle triggers live in migrate.ts. */
export const fundingPrepares = sqliteTable(
  "funding_prepares",
  {
    id: text("id").primaryKey(),
    scopeId: text("scope_id").notNull(),
    jobId: text("job_id").notNull(),
    jobIdHash: text("job_id_hash").notNull(),
    chainId: integer("chain_id").notNull(),
    escrow: text("escrow").notNull(),
    s01RecordSha256: text("s01_record_sha256").notNull(),
    s01ScheduleId: text("s01_schedule_id").notNull(),
    s01ScheduleTestnetOnly: integer("s01_schedule_testnet_only").notNull(),
    factory: text("factory").notNull(),
    implementation: text("implementation").notNull(),
    usdc: text("usdc").notNull(),
    payer: text("payer").notNull(),
    operator: text("operator").notNull(),
    termsHash: text("terms_hash").notNull(),
    policyNonce: text("policy_nonce").notNull(),
    prePolicyRoot: text("pre_policy_root").notNull(),
    acceptedPolicyDigest: text("accepted_policy_digest").notNull(),
    totalGross: text("total_gross").notNull(),
    quoteSnapshot: text("quote_snapshot").notNull(),
    configs: text("configs").notNull(),
    unitIds: text("unit_ids").notNull(),
    expiry: integer("expiry").notNull(),
    scopeExpiresAt: text("scope_expires_at").notNull(),
    finalityFS: integer("finality_f_s").notNull(),
    marginMS: integer("margin_m_s").notNull(),
    reclaimAtEarliest: integer("reclaim_at_earliest").notNull(),
    reclaimAtLatest: integer("reclaim_at_latest").notNull(),
    reconcileUntil: integer("reconcile_until").notNull(),
    typedDataDigest: text("typed_data_digest").notNull(),
    operatorSignature: text("operator_signature"),
    signatureVerifiedAt: text("signature_verified_at"),
    signedAt: text("signed_at"),
    servedPayload: blob("served_payload", { mode: "buffer" }),
    servedPayloadSha256: text("served_payload_sha256"),
    state: text("state", { enum: ["pending_signature", "served", "superseded", "expired"] }).notNull(),
    createdAt: text("created_at").notNull(),
    signatureRequestedAt: text("signature_requested_at"),
    endedAt: text("ended_at"),
    supersededBy: text("superseded_by"),
  },
  (t) => ({
    jobIdHashCheck: check("funding_prepares_job_id_hash_check", sql`job_id_hash = lower(job_id_hash) AND length(job_id_hash) = 66 AND substr(job_id_hash,1,2) = '0x' AND substr(job_id_hash,3) NOT GLOB '*[^0-9a-f]*'`),
    chainIdCheck: check("funding_prepares_chain_id_check", sql`chain_id > 0`),
    escrowCheck: check("funding_prepares_escrow_check", sql`escrow = lower(escrow) AND length(escrow) = 42 AND substr(escrow,1,2) = '0x' AND substr(escrow,3) NOT GLOB '*[^0-9a-f]*' AND escrow <> '0x0000000000000000000000000000000000000000'`),
    s01RecordSha256Check: check("funding_prepares_s01_record_sha256_check", sql`s01_record_sha256 = lower(s01_record_sha256) AND length(s01_record_sha256) = 64 AND s01_record_sha256 NOT GLOB '*[^0-9a-f]*'`),
    s01ScheduleTestnetOnlyCheck: check("funding_prepares_s01_schedule_testnet_only_check", sql`s01_schedule_testnet_only IN (0, 1)`),
    factoryCheck: check("funding_prepares_factory_check", sql`factory = lower(factory) AND length(factory) = 42 AND substr(factory,1,2) = '0x' AND substr(factory,3) NOT GLOB '*[^0-9a-f]*' AND factory <> '0x0000000000000000000000000000000000000000'`),
    implementationCheck: check("funding_prepares_implementation_check", sql`implementation = lower(implementation) AND length(implementation) = 42 AND substr(implementation,1,2) = '0x' AND substr(implementation,3) NOT GLOB '*[^0-9a-f]*' AND implementation <> '0x0000000000000000000000000000000000000000'`),
    usdcCheck: check("funding_prepares_usdc_check", sql`usdc = lower(usdc) AND length(usdc) = 42 AND substr(usdc,1,2) = '0x' AND substr(usdc,3) NOT GLOB '*[^0-9a-f]*' AND usdc <> '0x0000000000000000000000000000000000000000'`),
    payerCheck: check("funding_prepares_payer_check", sql`payer = lower(payer) AND length(payer) = 42 AND substr(payer,1,2) = '0x' AND substr(payer,3) NOT GLOB '*[^0-9a-f]*' AND payer <> '0x0000000000000000000000000000000000000000'`),
    operatorCheck: check("funding_prepares_operator_check", sql`operator = lower(operator) AND length(operator) = 42 AND substr(operator,1,2) = '0x' AND substr(operator,3) NOT GLOB '*[^0-9a-f]*' AND operator <> '0x0000000000000000000000000000000000000000'`),
    termsHashCheck: check("funding_prepares_terms_hash_check", sql`terms_hash = lower(terms_hash) AND length(terms_hash) = 66 AND substr(terms_hash,1,2) = '0x' AND substr(terms_hash,3) NOT GLOB '*[^0-9a-f]*'`),
    policyNonceCheck: check("funding_prepares_policy_nonce_check", sql`policy_nonce NOT GLOB '*[^0-9]*' AND length(policy_nonce) BETWEEN 1 AND 78 AND (policy_nonce = '0' OR substr(policy_nonce,1,1) <> '0')`),
    prePolicyRootCheck: check("funding_prepares_pre_policy_root_check", sql`pre_policy_root = lower(pre_policy_root) AND length(pre_policy_root) = 66 AND substr(pre_policy_root,1,2) = '0x' AND substr(pre_policy_root,3) NOT GLOB '*[^0-9a-f]*'`),
    acceptedPolicyDigestCheck: check("funding_prepares_accepted_policy_digest_check", sql`accepted_policy_digest = lower(accepted_policy_digest) AND length(accepted_policy_digest) = 66 AND substr(accepted_policy_digest,1,2) = '0x' AND substr(accepted_policy_digest,3) NOT GLOB '*[^0-9a-f]*'`),
    totalGrossCheck: check("funding_prepares_total_gross_check", sql`total_gross NOT GLOB '*[^0-9]*' AND length(total_gross) BETWEEN 1 AND 78 AND (total_gross = '0' OR substr(total_gross,1,1) <> '0')`),
    finalityFSCheck: check("funding_prepares_finality_f_s_check", sql`finality_f_s >= 0`),
    marginMSCheck: check("funding_prepares_margin_m_s_check", sql`margin_m_s >= 0`),
    typedDataDigestCheck: check("funding_prepares_typed_data_digest_check", sql`typed_data_digest = lower(typed_data_digest) AND length(typed_data_digest) = 66 AND substr(typed_data_digest,1,2) = '0x' AND substr(typed_data_digest,3) NOT GLOB '*[^0-9a-f]*'`),
    operatorSignatureCheck: check("funding_prepares_operator_signature_check", sql`operator_signature IS NULL OR (operator_signature = lower(operator_signature) AND length(operator_signature) = 132 AND substr(operator_signature,1,2) = '0x' AND substr(operator_signature,3) NOT GLOB '*[^0-9a-f]*')`),
    servedPayloadSha256Check: check("funding_prepares_served_payload_sha256_check", sql`served_payload_sha256 IS NULL OR (served_payload_sha256 = lower(served_payload_sha256) AND length(served_payload_sha256) = 64 AND served_payload_sha256 NOT GLOB '*[^0-9a-f]*')`),
    stateCheck: check("funding_prepares_state_check", sql`state IN ('pending_signature', 'served', 'superseded', 'expired')`),
    rowCheck1: check("funding_prepares_row_1_check", sql`reclaim_at_earliest <= reclaim_at_latest`),
    rowCheck2: check("funding_prepares_row_2_check", sql`expiry < reclaim_at_earliest`),
    rowCheck3: check("funding_prepares_row_3_check", sql`reconcile_until + finality_f_s <= reclaim_at_earliest`),
    rowCheck4: check("funding_prepares_row_4_check", sql`s01_schedule_testnet_only = 1 OR reconcile_until <= reclaim_at_earliest - 777600`),
    rowCheck5: check("funding_prepares_row_5_check", sql`json_valid(quote_snapshot) AND json_valid(configs) AND json_valid(unit_ids) AND json_type(unit_ids) = 'array'`),
    rowCheck6: check("funding_prepares_row_6_check", sql`served_payload IS NULL OR (typeof(served_payload) = 'blob' AND length(served_payload) > 0)`),
    rowCheck7: check("funding_prepares_row_7_check", sql`state <> 'served' OR (operator_signature IS NOT NULL AND signature_verified_at IS NOT NULL AND signed_at IS NOT NULL AND served_payload IS NOT NULL AND served_payload_sha256 IS NOT NULL)`),
    rowCheck8: check("funding_prepares_row_8_check", sql`state NOT IN ('superseded', 'expired') OR ended_at IS NOT NULL`),
    rowCheck9: check("funding_prepares_row_9_check", sql`(state = 'superseded') = (superseded_by IS NOT NULL)`),
    escrow: uniqueIndex("funding_prepares_escrow_uq").on(t.chainId, t.escrow),
    liveScope: uniqueIndex("funding_prepares_live_scope_uq").on(t.scopeId).where(sql`${t.state} IN ('pending_signature', 'served')`),
    job: index("funding_prepares_job_idx").on(t.jobId),
  }),
);
