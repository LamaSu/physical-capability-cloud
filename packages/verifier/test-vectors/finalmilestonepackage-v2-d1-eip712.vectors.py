# ─────────────────────────────── Keccak-256 (pure Python, stdlib only) ───────────────────────────────
_MASK64 = (1 << 64) - 1


def _rotl64(x, n):
    n %= 64
    if n == 0:
        return x & _MASK64
    return ((x << n) | (x >> (64 - n))) & _MASK64


def _build_rho_offsets():
    """FIPS 202 sec 3.2.2 Algorithm 2 (rho offset generation), not a transcribed flat table."""
    off = [[0] * 5 for _ in range(5)]  # off[x][y]
    x, y = 1, 0
    for t in range(24):
        off[x][y] = ((t + 1) * (t + 2) // 2) % 64
        x, y = y, (2 * x + 3 * y) % 5
    return off


_RHO = _build_rho_offsets()
_RC = [
    0x0000000000000001, 0x0000000000008082, 0x800000000000808A, 0x8000000080008000,
    0x000000000000808B, 0x0000000080000001, 0x8000000080008081, 0x8000000000008009,
    0x000000000000008A, 0x0000000000000088, 0x0000000080008009, 0x000000008000000A,
    0x000000008000808B, 0x800000000000008B, 0x8000000000008089, 0x8000000000008003,
    0x8000000000008002, 0x8000000000000080, 0x000000000000800A, 0x800000008000000A,
    0x8000000080008081, 0x8000000000008080, 0x0000000080000001, 0x8000000080008008,
]


def _keccak_f1600(lanes):
    """lanes: 25 ints (64-bit each), lanes[x + 5*y], mutated in place."""
    for rnd in range(24):
        c = [lanes[x] ^ lanes[x + 5] ^ lanes[x + 10] ^ lanes[x + 15] ^ lanes[x + 20] for x in range(5)]
        d = [c[(x - 1) % 5] ^ _rotl64(c[(x + 1) % 5], 1) for x in range(5)]
        for x in range(5):
            for y in range(5):
                lanes[x + 5 * y] ^= d[x]
        b = [0] * 25
        for x in range(5):
            for y in range(5):
                nx, ny = y, (2 * x + 3 * y) % 5
                b[nx + 5 * ny] = _rotl64(lanes[x + 5 * y], _RHO[x][y])
        for x in range(5):
            for y in range(5):
                lanes[x + 5 * y] = b[x + 5 * y] ^ ((~b[((x + 1) % 5) + 5 * y]) & b[((x + 2) % 5) + 5 * y] & _MASK64)
        lanes[0] ^= _RC[rnd]
    return lanes


def keccak256(data: bytes) -> bytes:
    rate = 136  # bytes; Keccak-256 capacity=512 bits=64 bytes, state=200 bytes, rate=200-64=136
    msg = bytearray(data)
    msg.append(0x01)  # original Keccak pad10*1 domain suffix (NOT NIST SHA3's 0x06 -- THE gotcha)
    while len(msg) % rate != 0:
        msg.append(0x00)
    msg[-1] ^= 0x80
    lanes = [0] * 25
    for block_start in range(0, len(msg), rate):
        block = msg[block_start:block_start + rate]
        for i in range(rate // 8):
            lanes[i] ^= int.from_bytes(block[8 * i:8 * i + 8], "little")
        _keccak_f1600(lanes)
    out = b""
    for i in range(4):  # squeeze 32 bytes = 4 lanes
        out += lanes[i].to_bytes(8, "little")
    return out


