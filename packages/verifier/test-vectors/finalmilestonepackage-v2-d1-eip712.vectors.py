TYPE_HASH = keccak256(TYPE_STRING.encode("utf-8"))
DOMAIN_TYPE_HASH = keccak256(b"EIP712Domain(string name,string version,uint256 chainId,address verifyingContract)")


def _enc_uint256(value) -> bytes:
    return int(value).to_bytes(32, "big")


def _enc_address(addr_hex: str) -> bytes:
    h = addr_hex[2:] if addr_hex.startswith("0x") else addr_hex
    b = bytes.fromhex(h)
    assert len(b) == 20, f"address must be 20 bytes, got {len(b)}"
    return b.rjust(32, b"\x00")


def _enc_bytes32(hex32: str) -> bytes:
    h = hex32[2:] if hex32.startswith("0x") else hex32
    b = bytes.fromhex(h)
    assert len(b) == 32, f"bytes32 must be 32 bytes, got {len(b)}"
    return b


def _enc_string_hashed(s: str) -> bytes:
    return keccak256(s.encode("utf-8"))


def _encode_field(ftype: str, value) -> bytes:
    if ftype == "uint256":
        return _enc_uint256(value)
    if ftype == "address":
        return _enc_address(value)
    if ftype == "bytes32":
        return _enc_bytes32(value)
    raise ValueError(f"unsupported field type {ftype}")


def hash_struct(message: dict) -> bytes:
    parts = [TYPE_HASH]
    for name, ftype in FIELDS:
        parts.append(_encode_field(ftype, message[name]))
    return keccak256(b"".join(parts))


def hash_domain(domain: dict) -> bytes:
    parts = [
        DOMAIN_TYPE_HASH,
        _enc_string_hashed(domain["name"]),
        _enc_string_hashed(domain["version"]),
        _enc_uint256(domain["chainId"]),
        _enc_address(domain["verifyingContract"]),
    ]
    return keccak256(b"".join(parts))


def eip712_digest(domain: dict, message: dict):
    ds = hash_domain(domain)
    sh = hash_struct(message)
    dg = keccak256(b"\x19\x01" + ds + sh)
    return dg, ds, sh


# ─────────────────────────────── D1 verifier (mirrors the JS mirror's gates exactly) ─────────────────
_ZERO_ADDRESS = "0x" + "00" * 20


def verify_d1(digest_bytes: bytes, sig_hex: str, expected_operator: str) -> dict:
    hexstr = (sig_hex[2:] if sig_hex.startswith("0x") else sig_hex).lower()
    if len(hexstr) != 130:
        return {"accepted": False, "reason": "bad_length", "recovered": None}
    r = int(hexstr[0:64], 16)
    s = int(hexstr[64:128], 16)
    v = int(hexstr[128:130], 16)
    if r == 0:
        return {"accepted": False, "reason": "r_zero", "recovered": None}
    if r >= SECP256K1_N:
        return {"accepted": False, "reason": "r_out_of_range", "recovered": None}
    if s == 0:
        return {"accepted": False, "reason": "s_zero", "recovered": None}
    if s >= SECP256K1_N:
        return {"accepted": False, "reason": "s_out_of_range", "recovered": None}
    if v != 27 and v != 28:
        return {"accepted": False, "reason": "v_not_27_or_28", "recovered": None}
    if s > SECP256K1_N2:
        return {"accepted": False, "reason": "high_s", "recovered": None}
    try:
        q = ecrecover(digest_bytes, r, s, v)
        recovered = address_from_point(q)
    except Exception as e:  # noqa: BLE001 -- deliberately broad: any recovery failure is a refusal, not a crash
        return {"accepted": False, "reason": "recovery_exception", "recovered": None, "detail": str(e)}
    if recovered.lower() == _ZERO_ADDRESS:
        return {"accepted": False, "reason": "zero_address", "recovered": recovered}
    if recovered.lower() != expected_operator.lower():
        return {"accepted": False, "reason": "signer_mismatch", "recovered": recovered}
    return {"accepted": True, "reason": None, "recovered": recovered}


def _is_valid_operator_principal_id_shape(s: str) -> bool:
    """^eip155:[0-9]+:0x[0-9a-f]{40}$ without `re` (not in the brief's allowed stdlib set)."""
    prefix = "eip155:"
    if not s.startswith(prefix):
        return False
    rest = s[len(prefix):]
    parts = rest.split(":")
    if len(parts) != 2:
        return False
    chain_part, addr_part = parts
    if len(chain_part) == 0 or not all(c in "0123456789" for c in chain_part):
        return False
    if not addr_part.startswith("0x"):
        return False
    hexpart = addr_part[2:]
    if len(hexpart) != 40:
        return False
    if not all(c in "0123456789abcdef" for c in hexpart):
        return False
    return True


def check_operator_principal_id(claimed: str, chain_id_decimal_str: str, recovered_addr: str) -> dict:
    if not _is_valid_operator_principal_id_shape(claimed):
        return {"ok": False, "reason": "operatorPrincipalId_not_lowercase"}
    canon = f"eip155:{chain_id_decimal_str}:{recovered_addr.lower()}"
    if claimed != canon:
        return {"ok": False, "reason": "operatorPrincipalId_mismatch"}
    return {"ok": True}


def verify_d1_entry(digest_bytes, sig_hex, expected_operator, claimed_operator_principal_id, claimed_signer_label, chain_id_decimal_str) -> dict:
    sig_check = verify_d1(digest_bytes, sig_hex, expected_operator)
    if not sig_check["accepted"]:
        return sig_check
    pc = check_operator_principal_id(claimed_operator_principal_id, chain_id_decimal_str, sig_check["recovered"])
    if not pc["ok"]:
        return {"accepted": False, "reason": pc["reason"], "recovered": sig_check["recovered"]}
    if claimed_signer_label.lower() != sig_check["recovered"].lower():
        return {"accepted": False, "reason": "signer_label_mismatch", "recovered": sig_check["recovered"]}
    return {"accepted": True, "reason": None, "recovered": sig_check["recovered"]}


