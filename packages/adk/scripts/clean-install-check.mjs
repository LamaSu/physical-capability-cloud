#!/usr/bin/env node
/**
 * Clean external install check for @pcc/adk (ledger R4, D1).
 *
 * Proves the public packages install and import in a project OUTSIDE this
 * workspace, the way an operator's project would, with no npm publish:
 *   1. build @pcc/spec, @pcc/kernel-sdk and @pcc/adk;
 *   2. `pnpm pack` each (pack rewrites workspace:* to real versions);
 *   3. boundary gate on every tarball: no "workspace:" anywhere, no @pcc/*
 *      dependency outside the packed set or private in the workspace, no chain
 *      client, and no key or env file in the payload;
 *   4. create a temp project outside the workspace that depends on the adk
 *      tarball, with pnpm.overrides pointing @pcc/spec and @pcc/kernel-sdk at
 *      their tarballs, and install it OFFLINE from the local pnpm store (no
 *      network; the third-party dependencies are the ones the workspace
 *      already resolved);
 *   5. import it from plain Node ESM, and type-check a TypeScript consumer
 *      against the installed declarations;
 *   6. digital-kernel scaffold (D3): generate a project from the INSTALLED
 *      @pcc/adk's scaffoldDigitalKernel, install it offline (same tarball
 *      overrides), build it, and dry-run it before AND after implementing
 *      execute.ts — proving the scaffold fails closed, then works, with no
 *      secret ever appearing in its own stdout.
 *
 *   node scripts/clean-install-check.mjs [--keep]
 *
 * Environment: PNPM_STORE_DIR (default: pnpm's own), TMPDIR for the temp
 * project. Exits non-zero on any failure.
 */
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync, statSync, chmodSync, symlinkSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve, relative, isAbsolute } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const repo = resolve(here, "../../..");
const keep = process.argv.includes("--keep");
const storeArgs = process.env.PNPM_STORE_DIR ? ["--store-dir", process.env.PNPM_STORE_DIR] : [];

const PACKED = [
  { name: "@pcc/spec", dir: "packages/spec" },
  { name: "@pcc/kernel-sdk", dir: "packages/kernel-sdk" },
  { name: "@pcc/adk", dir: "packages/adk" },
];
/** Chain clients must never ride along in the public kit. */
const CHAIN_CLIENTS = ["viem", "ethers", "wagmi", "web3", "@wagmi/core", "@coinbase/wallet-sdk", "@coinbase/cdp-sdk"];
/** Files that must never be in a public tarball. */
const FORBIDDEN_FILE = /(^|\/)(\.env(\..*)?|pcc-keys\.json|[^/]*\.pem|id_(rsa|ed25519)[^/]*)$/;

const failures = [];
const fail = (msg) => failures.push(msg);

function run(cmd, args, cwd, env) {
  return execFileSync(cmd, args, {
    cwd,
    env: env ? { ...process.env, ...env } : undefined,
    stdio: ["ignore", "pipe", "pipe"],
    encoding: "utf8",
  });
}

/**
 * Written into the consumer project (which already has the installed
 * @pcc/adk tarball in node_modules) and run as a subprocess, so
 * scaffoldDigitalKernel is imported from the INSTALLED package, never from
 * this repo's source tree.
 */
const SCAFFOLD_GEN_SCRIPT = [
  'import { scaffoldDigitalKernel } from "@pcc/adk";',
  'import { mkdirSync, writeFileSync } from "node:fs";',
  'import { dirname, join } from "node:path";',
  "",
  'const addr = "0x" + "ab".repeat(20);',
  "const opts = {",
  '  projectName: "adk-clean-install-scaffold-kernel",',
  '  kernelId: "k8-clean-install-check",',
  '  name: "Clean Install Check Kernel",',
  '  description:',
  '    "Generated by the @pcc/adk clean-install harness to prove the scaffold installs and runs outside the monorepo.",',
  '  capabilityType: "temperature-converter",',
  "  builder: {",
  "    agentId: `eip155:84532:${addr}`,",
  '    contactURI: "mailto:ci@example.invalid",',
  "    walletAddress: addr,",
  "  },",
  "  pricing: { baseUSD: 0.01 },",
  "  maxAssuranceTier: 1,",
  "  workflowSteps: [",
  '    { stepId: "run", stepType: "transform", description: "Run the kernel\'s single step", dependsOn: [] },',
  "  ],",
  "  search: {",
  '    source: "capabilities.search",',
  '    query: "temperature converter kernel",',
  "    at: new Date().toISOString(),",
  "    resultCount: 1,",
  '    resultIds: ["cap-example-1"],',
  "  },",
  '  versions: { spec: "^0.1.0", kernelSdk: "^0.1.0" },',
  "};",
  "",
  "const { files } = scaffoldDigitalKernel(opts);",
  "const outDir = process.argv[2];",
  "for (const [rel, content] of Object.entries(files)) {",
  "  const full = join(outDir, rel);",
  "  mkdirSync(dirname(full), { recursive: true });",
  "  writeFileSync(full, content);",
  "}",
  'console.log(JSON.stringify({ wrote: Object.keys(files).length, outDir }));',
  "",
].join("\n");

function workspacePrivateNames() {
  const names = new Set();
  for (const root of ["packages", "apps"]) {
    for (const entry of readdirSync(join(repo, root), { withFileTypes: true })) {
      const pj = join(repo, root, entry.name, "package.json");
      if (!entry.isDirectory() || !existsSync(pj)) continue;
      const p = JSON.parse(readFileSync(pj, "utf8"));
      if (p.private === true && p.name) names.add(p.name);
    }
  }
  return names;
}

function main() {
  const work = mkdtempSync(join(process.env.TMPDIR || tmpdir(), "adk-clean-install-"));
  const rel = relative(repo, work);
  if (!rel.startsWith("..") && !isAbsolute(rel)) {
    throw new Error(`temp project ${work} is inside the workspace ${repo}; set TMPDIR elsewhere`);
  }
  const tarballs = join(work, "tarballs");
  const project = join(work, "consumer");
  console.log(`work dir: ${work}`);

  try {
    // 1. Build.
    run("pnpm", ["--filter", "@pcc/spec", "--filter", "@pcc/kernel-sdk", "--filter", "@pcc/adk", "--workspace-concurrency=1", "build"], repo);

    // 2. Pack.
    const packed = {};
    for (const p of PACKED) {
      const out = run("pnpm", ["pack", "--pack-destination", tarballs], join(repo, p.dir)).trim().split("\n");
      const file = out.reverse().find((l) => l.trim().endsWith(".tgz"));
      if (!file) throw new Error(`pnpm pack printed no tarball for ${p.name}`);
      packed[p.name] = isAbsolute(file.trim()) ? file.trim() : join(tarballs, file.trim());
    }

    // 3. Boundary gate.
    const privateNames = workspacePrivateNames();
    for (const [name, tgz] of Object.entries(packed)) {
      const files = run("tar", ["-tzf", tgz], work).split("\n").filter(Boolean);
      for (const f of files) if (FORBIDDEN_FILE.test(f)) fail(`${name}: forbidden file in tarball: ${f}`);
      const pj = JSON.parse(run("tar", ["-xzOf", tgz, "package/package.json"], work));
      const raw = JSON.stringify(pj);
      if (raw.includes("workspace:")) fail(`${name}: packed package.json still contains "workspace:"`);
      const deps = { ...(pj.dependencies || {}), ...(pj.peerDependencies || {}), ...(pj.optionalDependencies || {}) };
      for (const dep of Object.keys(deps)) {
        if (dep.startsWith("@pcc/") && !(dep in packed)) fail(`${name}: depends on ${dep}, which is not part of the public kit`);
        if (dep.startsWith("@pcc/") && privateNames.has(dep) && dep !== "@pcc/adk") fail(`${name}: depends on private ${dep}`);
        if (CHAIN_CLIENTS.includes(dep)) fail(`${name}: depends on chain client ${dep}`);
      }
    }
    if (failures.length > 0) return;

    // 4. A consumer project outside the workspace, installed offline.
    run("mkdir", ["-p", project], work);
    const consumer = {
      name: "adk-clean-install-consumer",
      private: true,
      type: "module",
      dependencies: { "@pcc/adk": `file:${packed["@pcc/adk"]}` },
      pnpm: {
        overrides: {
          "@pcc/spec": `file:${packed["@pcc/spec"]}`,
          "@pcc/kernel-sdk": `file:${packed["@pcc/kernel-sdk"]}`,
        },
      },
    };
    writeFileSync(join(project, "package.json"), JSON.stringify(consumer, null, 2));
    run("pnpm", ["install", "--offline", "--ignore-workspace", ...storeArgs], project);
    for (const name of Object.keys(packed)) {
      const installed = join(project, "node_modules", ...name.split("/"), "package.json");
      if (!existsSync(installed)) {
        // Transitive @pcc packages live under .pnpm; find them through adk's own node_modules.
        continue;
      }
      if (readFileSync(installed, "utf8").includes("workspace:")) fail(`installed ${name} still says "workspace:"`);
    }
    if (readFileSync(join(project, "package.json"), "utf8").includes("workspace:")) fail("consumer package.json contains workspace:");

    // 5a. Import from plain Node ESM.
    writeFileSync(
      join(project, "check.mjs"),
      [
        'import * as adk from "@pcc/adk";',
        'const need = ["resolveToolRequest", "checkAgentPackage", "buildManifest", "registerKernel", "verifyBundleSignature"];',
        'for (const n of need) if (typeof adk[n] !== "function") throw new Error(`@pcc/adk does not export ${n}`);',
        'if (adk.AGENT_PACKAGE_PIN.toolCount !== Object.keys(adk.AGENT_TOOLS).length) throw new Error("pin/tool count mismatch");',
        'const r = adk.resolveToolRequest("setup_validate", { config: {} }, { baseUrl: "https://capability.network" });',
        'if (r.method !== "POST" || r.url !== "https://capability.network/api/setup/validate") throw new Error("bad request " + JSON.stringify(r));',
        'console.log(`ok: @pcc/adk imports; agent package ${adk.AGENT_PACKAGE_PIN.version} (${adk.AGENT_PACKAGE_PIN.toolCount} tools)`);',
      ].join("\n"),
    );
    console.log(run("node", ["check.mjs"], project).trim());

    // 5b. Type-check a TypeScript consumer against the installed declarations.
    writeFileSync(
      join(project, "check.ts"),
      [
        'import { resolveToolRequest, AGENT_PACKAGE_PIN, type ToolRequest, type AgentToolName } from "@pcc/adk";',
        'const name: AgentToolName = "setup_validate";',
        'const req: ToolRequest = resolveToolRequest(name, { config: {} }, { baseUrl: "https://capability.network" });',
        'const v: string = AGENT_PACKAGE_PIN.version;',
        "export { req, v };",
      ].join("\n"),
    );
    const tsc = join(repo, "node_modules", ".bin", "tsc");
    run(tsc, ["--noEmit", "--strict", "--module", "nodenext", "--moduleResolution", "nodenext", "--target", "es2022", "--skipLibCheck", "false", "check.ts"], project);
    console.log("ok: a TypeScript consumer type-checks against the installed declarations");

    // 6. Digital-kernel scaffold (D3 slice 1).
    //
    // 6.1: generate from the INSTALLED @pcc/adk (not this repo's source
    // tree) — run as a subprocess inside `project`, which already has
    // @pcc/adk resolved in node_modules from step 4.
    const scaffoldDir = join(work, "scaffolded-kernel");
    writeFileSync(join(project, "scaffold-gen.mjs"), SCAFFOLD_GEN_SCRIPT);
    console.log(run("node", ["scaffold-gen.mjs", scaffoldDir], project).trim());

    // 6.2: write already happened above (scaffold-gen.mjs writes the files
    // straight to scaffoldDir); now merge in pnpm.overrides so the two
    // @pcc/* deps resolve to the SAME local tarballs packed in step 2,
    // then install offline — no network, no real registry.
    const scaffoldPkgPath = join(scaffoldDir, "package.json");
    const scaffoldPkg = JSON.parse(readFileSync(scaffoldPkgPath, "utf8"));
    if (JSON.stringify(scaffoldPkg).includes("workspace:")) {
      fail("scaffold: generated package.json contains workspace:");
    }
    // scaffoldDigitalKernel() correctly declares semver ranges (never
    // workspace:/file:) for a REAL install. This is a lockfile-less,
    // --ignore-workspace install though, so pnpm re-resolves those ranges
    // from scratch; its metadata cache can name a newer patch version than
    // any tarball actually present in the offline store (ERR_PNPM_NO_OFFLINE_TARBALL).
    // Pin @types/node + typescript to the exact versions this repo's own
    // lockfile already resolved (and therefore already has cached), the
    // same way @pcc/spec + @pcc/kernel-sdk are pinned to their tarballs.
    const rootTypesNodeVersion = JSON.parse(readFileSync(join(repo, "node_modules/@types/node/package.json"), "utf8")).version;
    const rootTypescriptVersion = JSON.parse(readFileSync(join(repo, "node_modules/typescript/package.json"), "utf8")).version;
    scaffoldPkg.pnpm = {
      overrides: {
        "@pcc/spec": `file:${packed["@pcc/spec"]}`,
        "@pcc/kernel-sdk": `file:${packed["@pcc/kernel-sdk"]}`,
        "@types/node": rootTypesNodeVersion,
        typescript: rootTypescriptVersion,
      },
    };
    writeFileSync(scaffoldPkgPath, JSON.stringify(scaffoldPkg, null, 2));
    run("pnpm", ["install", "--offline", "--ignore-workspace", ...storeArgs], scaffoldDir);

    // 6.3: tsc build, then dry-run with a fresh (unimplemented) execute.ts.
    // A fresh scaffold fails closed: execute.ts throws "not implemented"
    // before any evidence bundle is assembled (job-handler.ts calls
    // execute() before minting/signing anything), so the fail-closed
    // choice here is NO bundle fields at all on the ok:false summary —
    // never a fabricated evidenceBundleHash/signatureValid for evidence
    // that was never produced. --dry-run mirrors that in its exit code:
    // it exits non-zero whenever ok:false, so a naive caller that only
    // checks $? still sees the kernel isn't ready.
    const keyFile = join(scaffoldDir, ".pcc", "kernel-key.json");
    const dryRunEnv = {
      PCC_KERNEL_ENDPOINT_URL: "https://example-kernel.invalid/run",
      PCC_KERNEL_KEY_FILE: keyFile,
    };
    run("pnpm", ["run", "build"], scaffoldDir);

    let firstOut;
    try {
      firstOut = run("node", ["dist/index.js", "--dry-run"], scaffoldDir, dryRunEnv);
      fail("scaffold: dry-run with unimplemented execute.ts should exit non-zero");
    } catch (e) {
      if (typeof e.stdout !== "string") throw e;
      firstOut = e.stdout;
    }
    let firstSummary;
    try {
      firstSummary = JSON.parse(firstOut.trim().split("\n").pop());
    } catch {
      throw new Error(`scaffold: first dry-run did not print JSON on its last stdout line: ${firstOut.slice(0, 2000)}`);
    }
    if (firstSummary.ok !== false) {
      fail(`scaffold: expected first dry-run ok=false, got ${JSON.stringify(firstSummary)}`);
    }
    if (!/not implemented/.test(firstSummary.error || "")) {
      fail(`scaffold: expected a "not implemented" error, got ${JSON.stringify(firstSummary)}`);
    }
    if ("evidenceBundleHash" in firstSummary || "signatureValid" in firstSummary || "kernelSessionPublicKey" in firstSummary) {
      fail(`scaffold: expected no bundle fields on a pre-signing failure (handler throws before signing), got ${JSON.stringify(firstSummary)}`);
    }
    console.log("ok: fresh scaffold fails closed on dry-run (execute.ts not implemented, no bundle fields)");
    const keyAfterFirstRun = readFileSync(keyFile, "utf8");

    // 6.4: implement execute.ts as an echo, rebuild, dry-run again.
    writeFileSync(
      join(scaffoldDir, "src", "execute.ts"),
      [
        "export async function execute(input: Record<string, unknown>): Promise<Record<string, unknown>> {",
        "  return input;",
        "}",
        "",
      ].join("\n"),
    );
    run("pnpm", ["run", "build"], scaffoldDir);
    const secondOut = run("node", ["dist/index.js", "--dry-run"], scaffoldDir, dryRunEnv);
    let secondSummary;
    try {
      secondSummary = JSON.parse(secondOut.trim().split("\n").pop());
    } catch {
      throw new Error(`scaffold: second dry-run did not print JSON on its last stdout line: ${secondOut.slice(0, 2000)}`);
    }
    if (secondSummary.ok !== true) {
      fail(`scaffold: expected second dry-run ok=true, got ${JSON.stringify(secondSummary)}`);
    }
    if (JSON.stringify(secondSummary.output) !== JSON.stringify({})) {
      fail(`scaffold: expected the empty dry-run input echoed back, got ${JSON.stringify(secondSummary.output)}`);
    }
    if (secondSummary.signatureValid !== true) {
      fail(`scaffold: expected signatureValid=true once execute.ts works, got ${JSON.stringify(secondSummary)}`);
    }
    console.log("ok: scaffold with execute.ts implemented dry-runs successfully and its evidence signature verifies");

    // 6.5: key file mode + no secret leakage into either dry-run's stdout.
    const keyStat = statSync(keyFile);
    if ((keyStat.mode & 0o777) !== 0o600) {
      fail(`scaffold: key file mode should be 0600, got 0${(keyStat.mode & 0o777).toString(8)}`);
    }
    const keyFileContents = JSON.parse(readFileSync(keyFile, "utf8"));
    const secretHex = keyFileContents.secretKey;
    if (typeof secretHex !== "string" || secretHex.length === 0) {
      fail("scaffold: key file has no secretKey to check for leakage against");
    } else if (firstOut.includes(secretHex) || secondOut.includes(secretHex)) {
      fail("scaffold: the principal secret key hex leaked into dry-run stdout");
    } else {
      console.log("ok: key file is 0600 and its secret key hex never appeared in dry-run stdout");
    }

    // 6.6 (lane review): the key file is reused, never rewritten, and a file
    // someone else could read or replace, a mismatched key pair, or a dangling
    // symlink stops the kernel before it signs anything.
    if (readFileSync(keyFile, "utf8") !== keyAfterFirstRun) {
      fail("scaffold: the second run rewrote an existing key file");
    } else {
      console.log("ok: an existing key file is reused byte for byte, never rewritten");
    }
    const refusedWith = (env, pattern, label) => {
      try {
        run("node", ["dist/index.js", "--dry-run"], scaffoldDir, env);
        fail(`scaffold: ${label}: dry-run should refuse, but it exited 0`);
      } catch (e) {
        const text = `${e.stdout || ""}${e.stderr || ""}`;
        if (!pattern.test(text)) fail(`scaffold: ${label}: expected ${pattern}, got ${text.slice(0, 500)}`);
        else console.log(`ok: ${label} is refused`);
      }
    };
    if (process.platform !== "win32") {
      for (const mode of [0o640, 0o620, 0o604]) {
        chmodSync(keyFile, mode);
        refusedWith(dryRunEnv, /group or other users can access it/, `a key file with mode 0${mode.toString(8)}`);
      }
      chmodSync(keyFile, 0o600);
    }
    const mismatched = join(scaffoldDir, ".pcc", "mismatched-key.json");
    writeFileSync(mismatched, JSON.stringify({ ...keyFileContents, publicKey: "00".repeat(32) }), { mode: 0o600 });
    refusedWith({ ...dryRunEnv, PCC_KERNEL_KEY_FILE: mismatched }, /does not belong to secretKey/, "a key file whose publicKey is not the secret key's");
    const dangling = join(scaffoldDir, ".pcc", "dangling-key.json");
    const danglingTarget = join(scaffoldDir, ".pcc", "nowhere", "target.json");
    symlinkSync(danglingTarget, dangling);
    refusedWith({ ...dryRunEnv, PCC_KERNEL_KEY_FILE: dangling }, /cannot be read/, "a dangling symlink at the key path");
    if (existsSync(danglingTarget)) fail("scaffold: a key was written through a dangling symlink");
  } catch (e) {
    fail(e && e.stderr ? `${e.message}\n${String(e.stderr).slice(0, 4000)}` : String(e));
  } finally {
    if (!keep) rmSync(work, { recursive: true, force: true });
    else console.log(`kept: ${work}`);
  }
}

main();
if (failures.length > 0) {
  console.error("clean-install check FAILED:");
  for (const f of failures) console.error(`  - ${f}`);
  process.exit(1);
}
console.log("clean-install check passed");
