#!/usr/bin/env node
/**
 * Generates src/generated/agent-pin.ts from the agent package the dashboard
 * serves (apps/dashboard/public/agent-package.json). The ADK never carries
 * hand-written tool JSON (#2392): it pins the package's version, tool count
 * and the sha256 of its exact bytes, plus each tool's endpoint.
 *
 * It refuses a package whose endpoints it cannot pin faithfully: a reserved,
 * malformed or duplicate tool name, an unknown method, a malformed required
 * list, or a path that is neither a well-formed gateway path nor an http(s)
 * URL (which the resolver keeps but refuses to call). The emitted values are
 * deeply frozen.
 *
 *   node scripts/generate-agent-pin.mjs          write the file
 *   node scripts/generate-agent-pin.mjs --check  exit 1 if the file is stale
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createHash } from "node:crypto";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
export const SOURCE = resolve(here, "../../../apps/dashboard/public/agent-package.json");
export const TARGET = resolve(here, "../src/generated/agent-pin.ts");

const byName = (a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0);

const TOOL_NAME = /^[a-z][a-z0-9_]*$/;
const RESERVED_NAMES = new Set(["__proto__", "constructor", "prototype"]);

// The endpoint rules. src/agent-package.ts applies the same rules when it
// resolves a call; the tests check that the two agree.
const METHODS = new Set(["GET", "POST", "PUT", "PATCH", "DELETE"]);
const LITERAL_SEGMENT = /^[A-Za-z0-9\-._~!$&'()*+,;=:@]+$/;
const PLACEHOLDER_SEGMENT = /^\{([A-Za-z_][A-Za-z0-9_]*)\}$/;

/** Why `path` (starting with one "/") is not a well-formed gateway path template, or null. */
export function gatewayPathProblem(path) {
  const names = new Set();
  for (const segment of path.slice(1).split("/")) {
    const placeholder = PLACEHOLDER_SEGMENT.exec(segment);
    if (placeholder) {
      if (names.has(placeholder[1])) return `repeats the placeholder {${placeholder[1]}}`;
      names.add(placeholder[1]);
    } else if (!LITERAL_SEGMENT.test(segment)) {
      return `has a segment that is empty or needs escaping: ${JSON.stringify(segment)}`;
    } else if (segment === "." || segment === "..") {
      return `has a dot segment: ${JSON.stringify(segment)}`;
    }
  }
  return null;
}

function isHttpUrl(text) {
  try {
    const url = new URL(text);
    return url.protocol === "http:" || url.protocol === "https:";
  } catch {
    return false;
  }
}

/** One tool's pinned endpoint. Throws when the tool cannot be pinned faithfully. */
function endpointOf(tool, seen) {
  const name = tool?.name;
  if (typeof name !== "string" || !TOOL_NAME.test(name) || RESERVED_NAMES.has(name)) {
    throw new Error(`bad tool name ${JSON.stringify(name)}: names are lower-case snake_case and not reserved`);
  }
  if (seen.has(name)) throw new Error(`duplicate tool name ${JSON.stringify(name)}`);
  seen.add(name);

  const rawMethod = tool.endpoint?.method;
  const method = typeof rawMethod === "string" ? rawMethod.toUpperCase() : "";
  if (!METHODS.has(method)) throw new Error(`tool ${JSON.stringify(name)}: bad method ${JSON.stringify(rawMethod)}`);

  const path = tool.endpoint?.path;
  if (typeof path === "string" && path.startsWith("/") && !path.startsWith("//")) {
    const problem = gatewayPathProblem(path);
    if (problem) throw new Error(`tool ${JSON.stringify(name)}: endpoint path ${JSON.stringify(path)} ${problem}`);
  } else if (typeof path !== "string" || !isHttpUrl(path)) {
    throw new Error(`tool ${JSON.stringify(name)}: endpoint path ${JSON.stringify(path)} is neither a gateway path nor an http(s) URL`);
  }

  const required = tool.input_schema?.required ?? [];
  if (
    !Array.isArray(required) ||
    !required.every((field) => typeof field === "string" && field !== "") ||
    new Set(required).size !== required.length
  ) {
    throw new Error(`tool ${JSON.stringify(name)}: required must be a list of distinct field names`);
  }
  return { method, path, required: [...required].sort() };
}

/** Render the pin module for the agent package's exact bytes. */
export function renderPin(bytes) {
  const sha256 = "sha256:" + createHash("sha256").update(bytes).digest("hex");
  const pkg = JSON.parse(bytes.toString("utf8"));
  if (typeof pkg?.version !== "string") throw new Error("the agent package has no version");
  if (!Array.isArray(pkg.tools)) throw new Error("the agent package has no tools list");
  const seen = new Set();
  const tools = [...pkg.tools].sort(byName).map((t) => ({ name: t?.name, ...endpointOf(t, seen) }));
  const out = [];
  out.push("// GENERATED by scripts/generate-agent-pin.mjs from apps/dashboard/public/agent-package.json.");
  out.push("// Do not edit. Regenerate with: pnpm --filter @pcc/adk generate");
  out.push("");
  out.push('import type { AgentToolEndpoint } from "../agent-package-types.js";');
  out.push('import { deepFreeze } from "../deep-freeze.js";');
  out.push("");
  out.push("export const AGENT_PACKAGE_PIN = deepFreeze({");
  out.push(`  schema: ${JSON.stringify(pkg.schema ?? null)},`);
  out.push(`  version: ${JSON.stringify(pkg.version)},`);
  out.push(`  toolCount: ${tools.length},`);
  out.push(`  sha256: ${JSON.stringify(sha256)},`);
  out.push("} as const);");
  out.push("");
  out.push("export const AGENT_TOOLS = deepFreeze({");
  for (const t of tools) {
    out.push(
      `  ${JSON.stringify(t.name)}: { method: ${JSON.stringify(t.method)}, ` +
        `path: ${JSON.stringify(t.path)}, required: ${JSON.stringify(t.required)} },`,
    );
  }
  out.push("} as const satisfies Record<string, AgentToolEndpoint>);");
  out.push("");
  out.push("export type AgentToolName = keyof typeof AGENT_TOOLS;");
  out.push("");
  return out.join("\n");
}

function main() {
  const rendered = renderPin(readFileSync(SOURCE));
  if (process.argv.includes("--check")) {
    const current = existsSync(TARGET) ? readFileSync(TARGET, "utf8") : "";
    if (current !== rendered) {
      console.error(
        "src/generated/agent-pin.ts is stale: the agent package changed. Run: pnpm --filter @pcc/adk generate",
      );
      process.exit(1);
    }
    console.log("agent pin is current");
    return;
  }
  writeFileSync(TARGET, rendered);
  console.log(`wrote ${TARGET}`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
