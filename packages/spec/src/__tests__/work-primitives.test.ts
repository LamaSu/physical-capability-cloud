/**
 * Hash-stability lock-in tests for the RFC-001 work primitives.
 *
 * THESE TESTS LOCK BYTE-LEVEL HASHES. Any future change to a primitive's
 * canonical-hash function will fail these tests, forcing a deliberate
 * version bump rather than a silent break of every JobSpec ever published.
 *
 * Coverage:
 *   1. WorkSchema   — computeWorkSchemaHash + assertWorkSchemaIsWellFormed
 *   2. WorkProduct  — computeWorkProductHash for all 4 kinds
 *   3. Registry     — computeSetSnapshotHash + computeMapSnapshotHash
 *   4. VerificationProgram — computeVerificationProgramHash
 *   5. JobSpec      — computeJobSpecHash
 *   6. Persona      — full HPLC lab tech JobSpec round-trip
 *
 * Hashes here were generated by running these tests once, capturing the
 * actual output, and pasting the bytes back. Re-generation requires a
 * deliberate version bump and updating the locked values.
 */

