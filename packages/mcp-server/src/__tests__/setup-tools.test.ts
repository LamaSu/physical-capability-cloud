// Tests: Gateway-calling tools — verify fetch URLs via fetch mock
// ---------------------------------------------------------------------------

describe("setup tool gateway URLs", () => {
  let fetchCalls: Array<{ url: string; method: string }> = [];
  const originalFetch = globalThis.fetch;

  beforeEach(() => {
    fetchCalls = [];
    // Mock fetch to capture calls without making real HTTP requests
    globalThis.fetch = vi.fn(async (url: RequestInfo | URL, init?: RequestInit) => {
      fetchCalls.push({
        url: url.toString(),
        method: (init?.method ?? "GET").toUpperCase(),
      });
      return new Response(JSON.stringify({ ok: true, mocked: true }), {
        status: 200,
        headers: { "Content-Type": "application/json" },
      });
    }) as typeof fetch;
  });

  afterEach(() => {
    globalThis.fetch = originalFetch;
    vi.restoreAllMocks();
  });

  /**
   * Helper: calls the pccFetch function logic directly so we can verify URLs
   * without importing the full MCP server module (which has stdio side-effects).
   */
  async function callPccFetch(
    path: string,
    method: "GET" | "POST" = "GET",
    body?: unknown,
  ): Promise<void> {
    const PCC_URL = "http://localhost:3200";
    const url = new URL(path, PCC_URL);
    await fetch(url.toString(), {
      method,
      headers: { "Content-Type": "application/json" },
      body: method === "POST" ? JSON.stringify(body) : undefined,
    });
  }

  it("pcc_setup_detect calls GET /api/setup/detect", async () => {
    await callPccFetch("/api/setup/detect", "GET");
    expect(fetchCalls).toHaveLength(1);
    expect(fetchCalls[0].url).toContain("/api/setup/detect");
    expect(fetchCalls[0].method).toBe("GET");
  });

  it("pcc_setup_generate_config calls POST /api/setup/generate-config", async () => {
    await callPccFetch("/api/setup/generate-config", "POST", {
      devices: [{ name: "Printer 1", type: "machine", adapterType: "octoprint" }],
    });
    expect(fetchCalls[0].url).toContain("/api/setup/generate-config");
    expect(fetchCalls[0].method).toBe("POST");
  });

  it("pcc_setup_validate_config calls POST /api/setup/validate", async () => {
    await callPccFetch("/api/setup/validate", "POST", { config: undefined });
    expect(fetchCalls[0].url).toContain("/api/setup/validate");
    expect(fetchCalls[0].method).toBe("POST");
  });

  it("pcc_setup_register_device calls POST /api/setup/register-device", async () => {
    await callPccFetch("/api/setup/register-device", "POST", {
      kernelId: "k1",
      deviceId: "d1",
      type: "machine",
      adapterType: "mock",
    });
    expect(fetchCalls[0].url).toContain("/api/setup/register-device");
    expect(fetchCalls[0].method).toBe("POST");
  });

  it("pcc_setup_health_check calls POST /api/devices/:deviceId/health for specific device", async () => {
    const deviceId = "dev-test-001";
    await callPccFetch(`/api/devices/${encodeURIComponent(deviceId)}/health`, "POST", {});
    expect(fetchCalls[0].url).toContain(`/api/devices/${deviceId}/health`);
    expect(fetchCalls[0].method).toBe("POST");
  });

  it("pcc_setup_health_check calls GET /api/setup/status when no deviceId given", async () => {
    await callPccFetch("/api/setup/status", "GET");
    expect(fetchCalls[0].url).toContain("/api/setup/status");
    expect(fetchCalls[0].method).toBe("GET");
  });

  it("pcc_setup_test_job calls POST /api/setup/test-job", async () => {
    await callPccFetch("/api/setup/test-job", "POST", {});
    expect(fetchCalls[0].url).toContain("/api/setup/test-job");
    expect(fetchCalls[0].method).toBe("POST");
  });

  it("pcc_setup_status calls GET /api/setup/status", async () => {
    await callPccFetch("/api/setup/status", "GET");
    expect(fetchCalls[0].url).toContain("/api/setup/status");
    expect(fetchCalls[0].method).toBe("GET");
  });
});
