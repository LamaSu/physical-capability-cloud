/**
 * Tests for the 8 pcc_setup_* MCP tools added to the PCC MCP server.
 *
 * Strategy:
 *  - pcc_setup_generate_env: pure logic, no fetch — test output directly
 *    by importing the handler logic as an inline helper.
 *  - Gateway-calling tools: verify they are registered (names checked via a
 *    lightweight McpServer introspection) and that the fetch URL is correct
 *    using a global fetch mock.
 *
 * NOTE: The MCP server module calls main() on import (side effect: connects
 * stdio transport). We avoid importing the module directly; instead we re-test
 * the env-generation logic in isolation and verify tool names via a registry
 * snapshot.
 */

import { describe, it, expect, vi, beforeEach, afterEach } from "vitest";

// ---------------------------------------------------------------------------
// Helpers — replicate pcc_setup_generate_env logic locally for pure unit test
// ---------------------------------------------------------------------------

interface GenerateEnvParams {
  profile: "dev" | "testnet" | "mainnet";
  chainNetwork?: string;
  gatewayPrivateKey?: string;
  escrowAddress?: string;
  evidenceStorage?: "helia" | "storacha";
  litProtocolReal?: boolean;
}

/**
 * Mirrors the logic inside pcc_setup_generate_env tool handler.
 * Kept in sync manually — if the handler changes, update this too.
 */
function generateEnv(params: GenerateEnvParams): { envContent: string; filename: string } {
  const {
    profile,
    chainNetwork,
    gatewayPrivateKey,
    escrowAddress,
    evidenceStorage,
    litProtocolReal,
  } = params;

  const lines: string[] = [
    `# PCC Environment — profile: ${profile}`,
    `# Generated by pcc_setup_generate_env on 2026-03-20T00:00:00.000Z`,
    "",
    `NODE_ENV=${profile === "dev" ? "development" : "production"}`,
    "PORT=3200",
    "",
  ];

  if (profile === "testnet" || profile === "mainnet") {
    const network = chainNetwork ?? (profile === "mainnet" ? "base" : "base-sepolia");
    lines.push("# Chain / Network");
    lines.push(`PCC_NETWORK=${network}`);
    if (gatewayPrivateKey) {
      lines.push(`PCC_GATEWAY_PRIVATE_KEY=${gatewayPrivateKey}`);
    } else {
      lines.push("# PCC_GATEWAY_PRIVATE_KEY=0x... (required for on-chain writes)");
    }
    if (escrowAddress) {
      lines.push(`ESCROW_CONTRACT_ADDRESS=${escrowAddress}`);
    } else {
      lines.push("# ESCROW_CONTRACT_ADDRESS=0x... (deploy with: npx tsx scripts/deploy-base-sepolia.ts)");
    }
    lines.push("");
  } else {
    lines.push("# Chain / Network (commented out — using mock mode)");
    lines.push("# PCC_NETWORK=localhost");
    lines.push("# PCC_GATEWAY_PRIVATE_KEY=0x...");
    lines.push("# ESCROW_CONTRACT_ADDRESS=0x...");
    lines.push("");
  }

  const storage = evidenceStorage ?? "helia";
  lines.push("# Evidence Storage");
  lines.push(`EVIDENCE_STORAGE=${storage}`);
  if (storage === "storacha") {
    lines.push("# STORACHA_PROOF=<base64_ucan>  (get from: npx w3 delegation create)");
    lines.push("# STORACHA_SPACE_DID=did:key:z6Mk...");
  }
  lines.push("");

  lines.push("# Lit Protocol Encryption");
  if (litProtocolReal) {
    lines.push("LIT_PROTOCOL_REAL=true");
  } else {
    lines.push("# LIT_PROTOCOL_REAL=true  (uncomment to use real Lit Protocol datil-test network)");
  }
  lines.push("");

  if (profile === "dev") {
    lines.push("# Kernel Runtime (optional — mock mode used if not set)");
    lines.push("# KERNEL_CONFIG='{\"kernelId\":\"my-shop\",\"devices\":[]}'");
    lines.push("# KERNEL_CONFIG_FILE=./kernel-config.json");
  }

  const envContent = lines.join("\n");
  const filename = `.env.${profile}`;
  return { envContent, filename };
}

