@_skip_no_nacl
def test_signer_shape_and_construction():
    pub_hex = _seed_pubkey_hex()
    cap = LogCapture("0x" + pub_hex, SEED_HEX)
    assert cap.signer == "0x" + pub_hex.lower()
    assert len(pub_hex) == 64  # raw 32-byte ed25519 pubkey, hex


@_skip_no_nacl
def test_chain_linkage_and_signatures_verify():
    import nacl.signing
    import nacl.exceptions

    pub_hex = _seed_pubkey_hex()
    vk = nacl.signing.SigningKey(bytes.fromhex(SEED_HEX)).verify_key
    cap = LogCapture("0x" + pub_hex, SEED_HEX)

    e0 = cap.capture("hello", "cups://job-1", "2026-07-09T00:00:00.000Z")
    e1 = cap.capture("world", "cups://job-1", "2026-07-09T00:01:00.000Z")
    p0, p1 = e0["payload"], e1["payload"]

    # Event envelope (WIRE SHAPE 3).
    assert e0["type"] == "log_hash_chain_entry"
    assert e0["timestamp"] == "2026-07-09T00:00:00.000Z"  # defaults to capturedAt

    # Chain linkage: first -> GENESIS, second -> first entryHash.
    assert p0["previousHash"] == GENESIS
    assert p1["previousHash"] == p0["entryHash"]

    # entryHash recompute matches (mirrors verifyLogChain check #1).
    assert p0["entryHash"] == compute_entry_hash("hello", "cups://job-1", "2026-07-09T00:00:00.000Z")
    assert p1["entryHash"] == compute_entry_hash("world", "cups://job-1", "2026-07-09T00:01:00.000Z")

    # kernelSignature shape (WIRE SHAPE 2/3).
    for p in (p0, p1):
        ks = p["kernelSignature"]
        assert ks["algorithm"] == "ed25519"
        assert ks["signer"] == "0x" + pub_hex.lower()
        assert len(ks["value"]) == 128  # 64-byte detached sig, hex

    # The signature verifies over the UTF-8 bytes of the entryHash STRING
    # (no EIP-191 / domain prefix) -- exactly what the oracle checks with noble.
    vk.verify(p0["entryHash"].encode("utf-8"), bytes.fromhex(p0["kernelSignature"]["value"]))
    vk.verify(p1["entryHash"].encode("utf-8"), bytes.fromhex(p1["kernelSignature"]["value"]))

    # A signature does NOT verify over a different message (tamper caught).
    with pytest.raises(nacl.exceptions.BadSignatureError):
        vk.verify((GENESIS).encode("utf-8"), bytes.fromhex(p0["kernelSignature"]["value"]))


@_skip_no_nacl
def test_redacted_omits_raw_content_but_keeps_hash_and_sig():
    import nacl.signing

    pub_hex = _seed_pubkey_hex()
    vk = nacl.signing.SigningKey(bytes.fromhex(SEED_HEX)).verify_key
    cap = LogCapture("0x" + pub_hex, SEED_HEX)

    ev = cap.capture(
        "secret payload", "cups://job-9", "2026-07-09T00:05:00.000Z", redacted=True
    )
    p = ev["payload"]
    assert "rawContent" not in p  # disclosure:redacted-commit
    # entryHash STILL commits to the real content, and the signature verifies.
    assert p["entryHash"] == compute_entry_hash(
        "secret payload", "cups://job-9", "2026-07-09T00:05:00.000Z"
    )
    vk.verify(p["entryHash"].encode("utf-8"), bytes.fromhex(p["kernelSignature"]["value"]))


# ---------------------------------------------------------------------------
# The HMAC dev fallback MUST be refused on the signing path (money path)
# ---------------------------------------------------------------------------

def test_signing_refuses_when_pynacl_absent(monkeypatch):
    """pynacl unavailable -> refuse to sign (never emit an HMAC as ed25519)."""
    monkeypatch.setattr(log_capture, "_HAS_NACL", False)
    with pytest.raises(LogSigningRefused):
        log_capture.sign_ed25519_utf8("sha256:" + "0" * 64, "0x" + "ab" * 32, "cd" * 32)
    with pytest.raises(LogSigningRefused):
        LogCapture("0x" + "ab" * 32, "cd" * 32)


@_skip_no_nacl
def test_signing_refuses_real_hmac_fallback_key(monkeypatch):
    """A genuine crypto.py HMAC-fallback key (public = sha256(secret)) is refused
    EVEN WITH pynacl available: the ed25519 public derived from the secret does
    not match, so signing would emit a signer that fails the oracle's match rule.
    """
    import pcc_node.crypto as crypto_mod

    monkeypatch.setattr(crypto_mod, "_HAS_NACL", False)
    pub, sec = crypto_mod.generate_node_keys()  # HMAC fallback shape
    # Confirm this really is the fallback shape: public == sha256(secret).
    assert pub == hashlib.sha256(bytes.fromhex(sec)).hexdigest()

    with pytest.raises(LogSigningRefused):
        LogCapture("0x" + pub, sec)
    with pytest.raises(LogSigningRefused):
        log_capture.sign_ed25519_utf8("sha256:" + "0" * 64, pub, sec)
