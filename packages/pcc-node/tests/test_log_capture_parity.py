"""Python<->TS hash parity + Ed25519 signing tests for the #52 log producer.

``goldens.json`` is generated by ``tests/gen_goldens.mjs`` from the VERBATIM
``canonicalize()`` of ``packages/spec/src/util/canonical.ts``. A mismatch on ANY
vector is a BLOCKER: the settlement lane is worthless if the producer's hashes
do not byte-match the TS verifier.

Regenerate goldens after any canonical.ts change:
    node packages/pcc-node/tests/gen_goldens.mjs
"""

import hashlib
import json
from pathlib import Path

import pytest

from pcc_node import log_capture
from pcc_node.log_capture import (
    GENESIS,
    LogCapture,
    LogSigningRefused,
    canonicalize,
    compute_entry_hash,
    _HAS_NACL,
)

_HERE = Path(__file__).resolve().parent
_GOLDENS = _HERE / "goldens.json"

# The oracle's existing golden (pcc-oracle log-chain-parity.test.ts:51) for
# computeLogEntryHash("hello", "cups://job-1", "2026-07-09T00:00:00.000Z").
ORACLE_SHARED_EXPECTED = (
    "sha256:c31408369756b766d5ee02b1403cbee4ab64ed39f9c3de0b7bee4605fdf3d9cd"
)
ORACLE_SHARED_RAW = "hello"
ORACLE_SHARED_SOURCE = "cups://job-1"
ORACLE_SHARED_CAP = "2026-07-09T00:00:00.000Z"

# Deterministic Ed25519 seed for signing round-trip tests (32 bytes).
SEED_HEX = "deadbeef" * 8

_skip_no_nacl = pytest.mark.skipif(not _HAS_NACL, reason="pynacl required")


def _load_goldens():
    # UTF-8 is MANDATORY: on Windows the default open() encoding is cp1252 and
    # would corrupt the non-ASCII / emoji fixtures before they reach the hasher.
    with open(_GOLDENS, encoding="utf-8") as f:
        return json.load(f)


_GOLDENS_DATA = _load_goldens()


def _seed_pubkey_hex():
    import nacl.signing
    import nacl.encoding

    sk = nacl.signing.SigningKey(bytes.fromhex(SEED_HEX))
    return sk.verify_key.encode(nacl.encoding.HexEncoder).decode("ascii")


# ---------------------------------------------------------------------------
# Parity — the money seam (BLOCKER on any mismatch)
# ---------------------------------------------------------------------------

def test_goldens_file_present():
    assert _GOLDENS.exists(), "goldens.json missing -- run: node tests/gen_goldens.mjs"


@pytest.mark.parametrize(
    "g", _GOLDENS_DATA["entry_hash"], ids=lambda g: g["name"]
)
def test_entry_hash_parity(g):
    got = compute_entry_hash(g["rawContent"], g["source"], g["capturedAt"])
    canonical = canonicalize(
        {"capturedAt": g["capturedAt"], "rawContent": g["rawContent"], "source": g["source"]}
    )
    assert got == g["expected"], (
        f"[{g['name']}] Python entryHash != TS golden.\n"
        f"  canonical(py) = {canonical!r}\n"
        f"  got      = {got}\n  expected = {g['expected']}"
    )


@pytest.mark.parametrize(
    "g", _GOLDENS_DATA["canonical"], ids=lambda g: g["name"]
)
def test_canonicalize_string_parity(g):
    got = canonicalize(g["value"])
    assert got == g["expected"], (
        f"[{g['name']}] Python canonicalize != TS canonicalize.\n"
        f"  got      = {got!r}\n  expected = {g['expected']!r}"
    )


def test_oracle_shared_vector_triple_lock():
    """oracle test == gen_goldens.mjs == Python, all on one vector."""
    # 1) Python reproduces the oracle's hardcoded golden directly.
    got = compute_entry_hash(ORACLE_SHARED_RAW, ORACLE_SHARED_SOURCE, ORACLE_SHARED_CAP)
    assert got == ORACLE_SHARED_EXPECTED
    # 2) The TS goldens file carries exactly this vector + digest.
    shared = next(
        g for g in _GOLDENS_DATA["entry_hash"] if g["name"] == "ascii_oracle_shared_vector"
    )
    assert shared["expected"] == ORACLE_SHARED_EXPECTED
    assert shared["rawContent"] == ORACLE_SHARED_RAW
    assert shared["source"] == ORACLE_SHARED_SOURCE
    assert shared["capturedAt"] == ORACLE_SHARED_CAP


def test_genesis_hash():
    assert GENESIS == "sha256:" + "0" * 64


def test_forward_slash_not_escaped():
    # Guards the most common divergence source: a URL-ish string must NOT escape /.
    assert canonicalize("cups://job/1") == '"cups://job/1"'


